.text
.globl _start

_start:

    # --------------------------------------------------------
    # ADD
    # --------------------------------------------------------
    # Test: x1 + x2 -> x3
    #
    # Expected:
    #   x3 = 7
    # --------------------------------------------------------

    addi x1, x0, 2
    addi x2, x0, 5
    add  x3, x1, x2


    # --------------------------------------------------------
    # SUB
    # --------------------------------------------------------
    # Test: x4 - x5 -> x6
    #
    # Expected:
    #   x6 = 3
    # --------------------------------------------------------

    addi x4, x0, 4
    addi x5, x0, 1
    sub  x6, x4, x5


    # --------------------------------------------------------
    # AND
    # --------------------------------------------------------
    # Test: x7 & x8 -> x9
    #
    # Expected:
    #   x9 = 7 #0111
    # --------------------------------------------------------

    addi x7, x0, 7 #0111
    addi x8, x0, 15 #1111
    and  x9, x7, x8


    # --------------------------------------------------------
    # OR
    # --------------------------------------------------------
    # Test: x10 | x11 -> x12
    #
    # Expected:
    #   x12 = 15 #01111
    # --------------------------------------------------------

    addi x10, x0, 13 #01101
    addi x11, x0, 6 #00110
    or   x12, x10, x11


    # --------------------------------------------------------
    # XOR
    # --------------------------------------------------------
    # Test: x13 ^ x14 -> x15
    #
    # Expected:
    #   x15 = 10 # 01010
    # --------------------------------------------------------

    addi x13, x0, 7 # 00111
    addi x14, x0, 13 # 01101
    xor  x15, x13, x14


    # --------------------------------------------------------
    # SLT
    # --------------------------------------------------------
    # Test: signed x16 < x17 -> x18
    #
    # Expected:
    #   x18 = 1
    # --------------------------------------------------------

    addi x16, x0, 5
    addi x17, x0, 14
    slt  x18, x16, x17


    # --------------------------------------------------------
    # END OF TEST
    # --------------------------------------------------------
    # Put the CPU into an infinite loop so the testbench
    # has time to inspect the register values.
    # --------------------------------------------------------

done:
    beq x0, x0, done
